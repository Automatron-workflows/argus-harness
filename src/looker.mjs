import { toCsv } from "./series.mjs";

const IDENT = /^[a-z][a-z0-9_]{1,63}$/;

function metricRows(catalog) {
  return [...catalog.values()].sort((a, b) => a.key.localeCompare(b.key));
}

function sqlString(value) {
  return `'${String(value)
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "''")
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n")}'`;
}

export function bigQueryDdl(catalog) {
  const metrics = metricRows(catalog);
  if (metrics.some((metric) => !IDENT.test(metric.key))) throw new Error("Metric keys must be lowercase snake_case");
  return `-- Generated by Argus Harness. Review before applying.
-- One semantic metric layer shared by the harness and Looker Studio.

CREATE TABLE IF NOT EXISTS metric_catalog (
  metric_key STRING NOT NULL,
  label STRING NOT NULL,
  description STRING NOT NULL,
  unit STRING NOT NULL,
  direction STRING NOT NULL,
  aggregation STRING NOT NULL,
  null_policy STRING NOT NULL,
  target_value FLOAT64,
  target_band ARRAY<FLOAT64>,
  target_label STRING,
  owner STRING NOT NULL,
  version INT64 NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS metric_daily (
  metric_key STRING NOT NULL,
  metric_date DATE NOT NULL,
  value FLOAT64,
  source STRING,
  computed_at TIMESTAMP
)
PARTITION BY metric_date
CLUSTER BY metric_key;

CREATE TABLE IF NOT EXISTS metric_status (
  metric_key STRING NOT NULL,
  state STRING NOT NULL,
  label STRING NOT NULL,
  detail STRING,
  coverage STRING,
  computed_at TIMESTAMP
);

CREATE OR REPLACE VIEW v_metric_latest AS
SELECT metric_key, metric_date, value, source, computed_at
FROM (
  SELECT
    metric_key,
    metric_date,
    value,
    source,
    computed_at,
    ROW_NUMBER() OVER (PARTITION BY metric_key ORDER BY metric_date DESC, computed_at DESC) AS rn
  FROM metric_daily
)
WHERE rn = 1;

CREATE OR REPLACE VIEW v_metric_daily AS
SELECT
  d.metric_key,
  c.label,
  c.unit,
  c.direction,
  c.aggregation,
  c.null_policy,
  d.metric_date,
  d.value,
  d.source,
  d.computed_at
FROM metric_daily d
LEFT JOIN metric_catalog c USING (metric_key);

CREATE OR REPLACE VIEW v_metric_health AS
SELECT
  l.metric_key,
  c.label,
  l.metric_date AS latest_date,
  l.value AS latest_value,
  l.source,
  l.computed_at,
  s.state,
  s.label AS status_label,
  s.detail AS status_detail,
  s.coverage,
  DATE_DIFF(CURRENT_DATE(), l.metric_date, DAY) AS days_since_latest
FROM v_metric_latest l
LEFT JOIN metric_catalog c USING (metric_key)
LEFT JOIN metric_status s USING (metric_key);

-- Seed the catalog from the harness contract. Review labels and descriptions.
${metrics
  .map(
    (metric) =>
      `INSERT INTO metric_catalog (metric_key, label, description, unit, direction, aggregation, null_policy, target_value, target_band, target_label, owner, version)
VALUES (${[
        metric.key,
        metric.label,
        metric.description,
        metric.unit,
        metric.direction,
        metric.aggregation,
        metric.nullPolicy,
        metric.target?.value ?? null,
        metric.target?.band ? `[${metric.target.band.join(", ")}]` : null,
        metric.target?.label ?? null,
        metric.owner,
        metric.version,
      ]
        .map((value) => (value === null ? "NULL" : typeof value === "number" ? String(value) : sqlString(value)))
        .join(", ")});`,
  )
  .join("\n")}
`;
}

export function lookerFields(catalog) {
  return metricRows(catalog).map((metric) => ({
    name: metric.key,
    label: metric.label,
    type: "NUMBER",
    semanticType:
      metric.unit === "currency_eur"
        ? "CURRENCY_EUR"
        : metric.unit === "percent"
          ? "PERCENT"
          : metric.unit === "days"
            ? "DURATION_DAYS"
            : metric.unit === "months"
              ? "NUMBER"
              : metric.unit === "hours"
                ? "DURATION_HOURS"
                : metric.unit === "duration_s"
                  ? "DURATION_SECONDS"
                  : metric.unit === "ratio"
                    ? "RATIO"
                    : "NUMBER",
    aggregation: metric.aggregation === "cumulative" ? "MAX" : metric.aggregation === "average" ? "AVERAGE" : metric.aggregation === "sum" ? "SUM" : "LATEST",
    description: `${metric.description} Null policy: ${metric.nullPolicy}. Owner: ${metric.owner}.`,
    unit: metric.unit,
    direction: metric.direction,
    target: metric.target ?? null,
  }));
}

export function lookerFieldsCsv(catalog) {
  return toCsv(
    ["field", "label", "type", "semantic_type", "default_aggregation", "unit", "direction", "description"],
    lookerFields(catalog).map((field) => [
      field.name,
      field.label,
      field.type,
      field.semanticType,
      field.aggregation,
      field.unit,
      field.direction,
      field.description,
    ]),
  );
}

