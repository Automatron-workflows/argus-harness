/**
 * Portable warehouse DDL for the non-BigQuery providers. BigQuery has its own
 * catalog/views generator in looker.mjs because it uses ARRAY and partitioning.
 */

const TYPES = {
  snowflake: { text: "VARCHAR", float: "FLOAT", int: "INTEGER", date: "DATE", timestamp: "TIMESTAMP_NTZ", now: "CURRENT_TIMESTAMP()", days: "DATEDIFF('day', l.metric_date, CURRENT_DATE())" },
  postgres: { text: "TEXT", float: "DOUBLE PRECISION", int: "INTEGER", date: "DATE", timestamp: "TIMESTAMPTZ", now: "CURRENT_TIMESTAMP", days: "(CURRENT_DATE - l.metric_date)" },
  redshift: { text: "VARCHAR", float: "DOUBLE PRECISION", int: "INTEGER", date: "DATE", timestamp: "TIMESTAMP", now: "CURRENT_TIMESTAMP", days: "(CURRENT_DATE - l.metric_date)" },
  duckdb: { text: "VARCHAR", float: "DOUBLE", int: "INTEGER", date: "DATE", timestamp: "TIMESTAMP", now: "CURRENT_TIMESTAMP", days: "(CURRENT_DATE - l.metric_date)" },
};

function sqlString(value) {
  return `'${String(value)
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "''")
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n")}'`;
}

function value(value) {
  if (value === null || value === undefined) return "NULL";
  return typeof value === "number" ? String(value) : sqlString(value);
}

export function warehouseDdl(dialect, catalog) {
  const type = TYPES[dialect];
  if (!type) throw new Error(`Unsupported warehouse dialect "${dialect}". Use snowflake, postgres, redshift or duckdb.`);
  const metrics = [...catalog.values()].sort((a, b) => a.key.localeCompare(b.key));
  const inserts = metrics
    .map(
      (metric) => `INSERT INTO metric_catalog (metric_key, label, description, unit, direction, aggregation, null_policy, target_value, target_band_low, target_band_high, target_label, owner, version)
VALUES (${[
        metric.key,
        metric.label,
        metric.description,
        metric.unit,
        metric.direction,
        metric.aggregation,
        metric.nullPolicy,
        metric.target?.value ?? null,
        metric.target?.band?.[0] ?? null,
        metric.target?.band?.[1] ?? null,
        metric.target?.label ?? null,
        metric.owner,
        metric.version,
      ]
        .map(value)
        .join(", ")});`,
    )
    .join("\n");
  return `-- Generated by Argus Harness for ${dialect}. Review before applying.
-- One semantic metric layer shared by the harness and Looker Studio.

CREATE TABLE IF NOT EXISTS metric_catalog (
  metric_key ${type.text} NOT NULL,
  label ${type.text} NOT NULL,
  description ${type.text} NOT NULL,
  unit ${type.text} NOT NULL,
  direction ${type.text} NOT NULL,
  aggregation ${type.text} NOT NULL,
  null_policy ${type.text} NOT NULL,
  target_value ${type.float},
  target_band_low ${type.float},
  target_band_high ${type.float},
  target_label ${type.text},
  owner ${type.text} NOT NULL,
  version ${type.int} NOT NULL,
  updated_at ${type.timestamp} NOT NULL DEFAULT ${type.now}
);

CREATE TABLE IF NOT EXISTS metric_daily (
  metric_key ${type.text} NOT NULL,
  metric_date ${type.date} NOT NULL,
  value ${type.float},
  source ${type.text},
  computed_at ${type.timestamp}
);

CREATE TABLE IF NOT EXISTS metric_status (
  metric_key ${type.text} NOT NULL,
  state ${type.text} NOT NULL,
  label ${type.text} NOT NULL,
  detail ${type.text},
  coverage ${type.text},
  computed_at ${type.timestamp}
);

CREATE OR REPLACE VIEW v_metric_latest AS
SELECT metric_key, metric_date, value, source, computed_at
FROM (
  SELECT
    metric_key,
    metric_date,
    value,
    source,
    computed_at,
    ROW_NUMBER() OVER (PARTITION BY metric_key ORDER BY metric_date DESC, computed_at DESC) AS rn
  FROM metric_daily
) ranked
WHERE rn = 1;

CREATE OR REPLACE VIEW v_metric_daily AS
SELECT
  d.metric_key,
  c.label,
  c.unit,
  c.direction,
  c.aggregation,
  c.null_policy,
  d.metric_date,
  d.value,
  d.source,
  d.computed_at
FROM metric_daily d
LEFT JOIN metric_catalog c USING (metric_key);

CREATE OR REPLACE VIEW v_metric_health AS
SELECT
  l.metric_key,
  c.label,
  l.metric_date AS latest_date,
  l.value AS latest_value,
  l.source,
  l.computed_at,
  s.state,
  s.label AS status_label,
  s.detail AS status_detail,
  s.coverage,
  ${type.days} AS days_since_latest
FROM v_metric_latest l
LEFT JOIN metric_catalog c USING (metric_key)
LEFT JOIN metric_status s USING (metric_key);

-- Seed the catalog once. Review labels and descriptions before applying.
${inserts}
`;
}
